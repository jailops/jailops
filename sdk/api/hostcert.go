// The certificate of the console and the API (extension host_certificate; docs/exposure.md). The TLS listener serves
// one of: the self-signed certificate the daemon generates, the files listen.https.cert and key of jailopsd.yaml name,
// a certificate an administrator uploaded, or one the daemon obtains with ACME (RFC 8555) from a public CA.
// GET /api/v1/host/certificate reads it, PUT uploads a certificate and its key, POST /api/v1/host/certificate/acme
// turns ACME on, POST /api/v1/host/certificate/self-signed goes back to the generated certificate.

// CertificateSource says where the served certificate comes from.
type CertificateSource string

const (
	CertSourceSelfSigned CertificateSource = "self-signed" // generated by the daemon on first start
	CertSourceConfigured CertificateSource = "configured"  // listen.https.cert and key of jailopsd.yaml
	CertSourceUploaded   CertificateSource = "uploaded"    // uploaded through the API or the console
	CertSourceACME       CertificateSource = "acme"        // obtained and renewed with ACME
)

// ACMEChallenge is how the CA checks that the host answers for a name.
type ACMEChallenge string

const (
	// ACMEHTTP01 answers on port 80 (redirected to the daemon's challenge listener).
	ACMEHTTP01 ACMEChallenge = "http-01"
	// ACMETLSALPN01 answers on port 443 (redirected to the daemon's TLS listener).
	ACMETLSALPN01 ACMEChallenge = "tls-alpn-01"
)

// The directories of the default CA. Production is the default; staging issues untrusted certificates under
// generous rate limits, for trying the setup.
const (
	ACMEDirectoryProduction = "https://acme-v02.api.letsencrypt.org/directory"
	ACMEDirectoryStaging    = "https://acme-staging-v02.api.letsencrypt.org/directory"
)

// Limits of the certificate routes.
const (
	MaxACMEDomains = 20
	// MaxCertificatePEM bounds an upload (certificate chain and key together).
	MaxCertificatePEM = 64 << 10
	// MaxCertificateChain is the number of certificates an uploaded chain may hold.
	MaxCertificateChain = 8
	// ACMERenewBefore is how long before expiry an ACME certificate is renewed.
	ACMERenewBefore = 30 * 24 * time.Hour
)

// ACMESpec is the ACME setting: listen.https.acme of jailopsd.yaml, or what an administrator stored with
// POST /api/v1/host/certificate/acme.
type ACMESpec struct {
	Enabled bool `json:"enabled" yaml:"enabled"`
	// Email is the contact of the account (optional): the CA may write about the account and its certificates.
	Email string `json:"email,omitempty" yaml:"email,omitempty"`
	// Domains are the DNS names of the certificate, 1 to 20. Every name must resolve to this host from the
	// internet. No wildcards: they need the dns-01 challenge, which JailOps does not offer.
	Domains []string `json:"domains" yaml:"domains"`
	// DirectoryURL is the CA's ACME directory (default ACMEDirectoryProduction); https only.
	DirectoryURL string `json:"directory_url,omitempty" yaml:"directory_url,omitempty"`
	// Challenge is http-01 (default) or tls-alpn-01.
	Challenge ACMEChallenge `json:"challenge,omitempty" yaml:"challenge,omitempty"`
	// AcceptTOS must be true: the administrator agrees to the CA's terms of service (TermsURL of the status).
	AcceptTOS bool `json:"accept_tos" yaml:"accept_tos"`
}

// ValidACMEDomain checks one name of a certificate: a DNS name of two labels or more, not an address, no wildcard.
func ValidACMEDomain(d string) error {
	if strings.HasPrefix(d, "*.") {
		return Errorf(CodeUnsupported, "%q is a wildcard name: wildcards need the dns-01 challenge, which JailOps does not offer", d).
			WithHint("list each name the console is reached by, or use your own certificate (upload one)")
	}
	if _, err := netip.ParseAddr(strings.Trim(d, "[]")); err == nil {
		return Errorf(CodeInvalid, "%q is an address: ACME certificates here are for DNS names only", d)
	}
	if !ValidDNSName(d) {
		return Errorf(CodeInvalid, "%q is not a DNS name (letters, digits and hyphens, labels of at most 63 characters)", d)
	}
	if !strings.Contains(d, ".") {
		return Errorf(CodeInvalid, "%q is not a fully qualified name (a CA issues only for names under a public domain)", d)
	}
	return nil
}

// ValidACMEEmail checks a contact address: a plain address (no display name), with a domain of two labels or more.
func ValidACMEEmail(e string) error {
	a, err := mail.ParseAddress(e)
	if err != nil || a.Name != "" || a.Address != e || len(e) > 254 || strings.ContainsAny(e, " \t\r\n<>\"") {
		return Errorf(CodeInvalid, "%q is not an email address", e)
	}
	_, dom, _ := strings.Cut(e, "@")
	if !strings.Contains(dom, ".") {
		return Errorf(CodeInvalid, "%q is not an email address with a domain", e)
	}
	return nil
}

// ValidACMEDirectory checks a directory URL: absolute https, with a host, without credentials or a fragment.
func ValidACMEDirectory(u string) error {
	p, err := url.Parse(u)
	if err != nil || p.Scheme != "https" || p.Host == "" || p.User != nil || p.Fragment != "" || strings.ContainsAny(u, " \t\r\n") {
		return Errorf(CodeInvalid, "directory_url %q must be an https URL", u)
	}
	return nil
}

// Validate checks the setting; Canonical fills in the defaults. A disabled setting may be incomplete.
func (a ACMESpec) Validate() error {
	c := a.Canonical()
	if c.Challenge != ACMEHTTP01 && c.Challenge != ACMETLSALPN01 {
		return Errorf(CodeInvalid, "challenge %q is not http-01 or tls-alpn-01", a.Challenge).
			WithHint("dns-01 is not offered")
	}
	if err := ValidACMEDirectory(c.DirectoryURL); err != nil {
		return err
	}
	if c.Email != "" {
		if err := ValidACMEEmail(c.Email); err != nil {
			return err
		}
	}
	if len(c.Domains) > MaxACMEDomains {
		return Errorf(CodeInvalid, "at most %d domains, not %d", MaxACMEDomains, len(c.Domains))
	}
	for i, d := range c.Domains {
		if err := ValidACMEDomain(d); err != nil {
			return err
		}
		if slices.Contains(c.Domains[:i], d) {
			return Errorf(CodeInvalid, "domain %s is listed twice", d)
		}
	}
	if !a.Enabled {
		return nil
	}
	if len(c.Domains) == 0 {
		return Errorf(CodeInvalid, "ACME needs at least one domain: the name the console is reached by")
	}
	if !a.AcceptTOS {
		return Errorf(CodeInvalid, "accept_tos must be true: ACME needs your agreement to the CA's terms of service").
			WithHint("read the terms (the directory names them), then set accept_tos: true")
	}
	return nil
}

// Canonical returns the setting with its defaults: the production directory, http-01, lower-case domains.
func (a ACMESpec) Canonical() ACMESpec {
	out := a
	out.Email = strings.TrimSpace(a.Email)
	if out.DirectoryURL == "" {
		out.DirectoryURL = ACMEDirectoryProduction
	}
	if out.Challenge == "" {
		out.Challenge = ACMEHTTP01
	}
	out.Domains = nil
	for _, d := range a.Domains {
		out.Domains = append(out.Domains, strings.ToLower(strings.TrimSpace(d)))
	}
	return out
}

// ACMEChallengePort is the port the CA connects to for a challenge: 80 for http-01, 443 for tls-alpn-01.
func ACMEChallengePort(c ACMEChallenge) int {
	if c == ACMETLSALPN01 {
		return 443
	}
	return 80
}

// ACMERedirectLines are the pf lines an administrator adds to /etc/pf.conf, after the line anchor "jailops/*", when the
// host firewall module does not manage the file: the CA's port is redirected to the daemon's port on the loopback
// addresses, where an unprivileged listener can answer. "pass in quick" lets the redirected connection through the filter.
func ACMERedirectLines(c ACMEChallenge, port int) []string {
	from := ACMEChallengePort(c)
	return []string{
		fmt.Sprintf("pass in quick inet proto tcp from any to (self) port %d rdr-to 127.0.0.1 port %d", from, port),
		fmt.Sprintf("pass in quick inet6 proto tcp from any to (self) port %d rdr-to ::1 port %d", from, port),
	}
}

// CertificateInfo describes a certificate.
type CertificateInfo struct {
	Subject string `json:"subject"`
	Issuer  string `json:"issuer"`
	// Names are the DNS names and addresses it is valid for.
	Names     []string  `json:"names"`
	NotBefore time.Time `json:"not_before"`
	NotAfter  time.Time `json:"not_after"`
	// DaysLeft is the number of whole days to NotAfter (negative once expired).
	DaysLeft int `json:"days_left"`
	// Fingerprint is the hex SHA-256 of the leaf (what a client pins).
	Fingerprint string `json:"fingerprint"`
	SelfSigned  bool   `json:"self_signed"`
	// PublicCA is true when the chain verifies against the host's trusted roots: clients need no pin.
	PublicCA bool `json:"public_ca"`
}

// ACMEStatus is the state of ACME.
type ACMEStatus struct {
	Spec ACMESpec `json:"spec"`
	// State is idle (nothing to do), requesting (an order runs), valid (the certificate is current) or error (the
	// last attempt failed; see LastError and NextAttempt).
	State       string     `json:"state"`
	LastAttempt *time.Time `json:"last_attempt,omitempty"`
	LastSuccess *time.Time `json:"last_success,omitempty"`
	LastError   string     `json:"last_error,omitempty"`
	// Failures counts the attempts that failed in a row; the next one waits longer each time.
	Failures    int        `json:"failures,omitempty"`
	NextAttempt *time.Time `json:"next_attempt,omitempty"`
	// RenewAt is when the current certificate is renewed (30 days before it expires).
	RenewAt *time.Time `json:"renew_at,omitempty"`
	// ChallengePort is the daemon's port the CA's port is redirected to: the challenge listener (http-01) or the
	// TLS listener (tls-alpn-01).
	ChallengePort int `json:"challenge_port"`
	// TermsURL is the CA's terms of service, when the directory was read.
	TermsURL string `json:"terms_url,omitempty"`
}

// ACMERedirect says how the CA's port reaches the daemon.
type ACMERedirect struct {
	// Managed is true when the host firewall module renders the redirect (it owns /etc/pf.conf).
	Managed bool `json:"managed"`
	// Applied is true when the firewall applied last has the redirect; false means: apply the firewall again.
	Applied bool `json:"applied"`
	// Lines are what the administrator adds to /etc/pf.conf when the module does not manage it.
	Lines []string `json:"lines,omitempty"`
}

// HostCertificate is GET /api/v1/host/certificate and the answer of its changes.
type HostCertificate struct {
	Kind   Kind              `json:"kind"`
	Source CertificateSource `json:"source"`
	// Current is the certificate the TLS listener serves now.
	Current CertificateInfo `json:"current"`
	// ACME is set while ACME is the source (or the file enables it).
	ACME *ACMEStatus `json:"acme,omitempty"`
	// Redirect is set with ACME: how the CA's port reaches the daemon.
	Redirect *ACMERedirect `json:"redirect,omitempty"`
	// Configured is true when jailopsd.yaml names the certificate files: the console cannot change them.
	Configured bool `json:"configured"`
	// Stored is true when the source was chosen through the API; that choice wins over listen.https.acme of
	// jailopsd.yaml.
	Stored bool `json:"stored,omitempty"`
	// Listener is false when the daemon has no TLS listener (listen.https.address is empty); Port is its port.
	Listener bool `json:"listener"`
	Port     int  `json:"port,omitempty"`
	// RemoteAdd is the command a client uses to add this host: without a fingerprint when a public CA signed the
	// certificate (clients must not pin a certificate that is renewed), with the pin otherwise.
	RemoteAdd string   `json:"remote_add,omitempty"`
	Warnings  []string `json:"warnings,omitempty"`
}

// HostCertificateUpload is the body of PUT /api/v1/host/certificate: a PEM certificate chain (leaf first) and its
// PEM private key. Hostname is the name clients use: the certificate must be valid for it.
type HostCertificateUpload struct {
	Certificate string `json:"certificate"`
	Key         string `json:"key"`
	Hostname    string `json:"hostname"`
}
