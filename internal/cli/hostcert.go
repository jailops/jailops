// The certificate of this host's console and API (docs/exposure.md): show it, obtain one with ACME, upload one,
// or go back to the self-signed one. The changes need a global administrator.

func (a *app) hostCertificateCmd() *cobra.Command {
	cc := group("certificate", "Show and replace the certificate of the console and the API",
		`The TLS listener of jailopsd (the console and the API, port 39110) serves one
certificate: the self-signed one the daemon generates, one you upload, one the
daemon obtains and renews with ACME from a public CA, or the files
listen.https.cert and key of jailopsd.yaml name (then nothing here changes it).

'show' prints what is served and how clients add this host. The changes need a
global administrator and take effect from the next connection on, without a
restart.`,
		`jailops host certificate show
jailops host certificate acme --domain console.example.com --email admin@example.com --accept-tos
jailops host certificate upload --cert fullchain.pem --key privkey.pem
jailops host certificate self-signed`, "cert", "certificates")
	cc.AddCommand(a.hostCertShow(), a.hostCertACME(), a.hostCertUpload(), a.hostCertSelfSigned())
	return cc
}

// certMode says where the served certificate comes from, in words.
func certMode(st api.HostCertificate) string {
	switch st.Source {
	case api.CertSourceSelfSigned:
		return "self-signed (generated by the daemon)"
	case api.CertSourceConfigured:
		return "configured (listen.https.cert and key of jailopsd.yaml)"
	case api.CertSourceUploaded:
		return "uploaded"
	case api.CertSourceACME:
		return "ACME (obtained and renewed from a public CA)"
	}
	return string(st.Source)
}

// printCertificate writes the human form of the certificate status.
func (a *app) printCertificate(w io.Writer, st api.HostCertificate) {
	s := showWriter{w: w, width: 12}
	when := func(t *time.Time) string {
		if t == nil || t.IsZero() {
			return "-"
		}
		return t.UTC().Format("2006-01-02 15:04 MST")
	}
	cur := st.Current
	s.title("Certificate of this host: %s", certMode(st))
	s.kv("Subject", dash(cur.Subject))
	s.kv("Names", joinOrDash(cur.Names))
	s.kv("Issuer", dash(cur.Issuer))
	valid := "-"
	if !cur.NotAfter.IsZero() {
		valid = fmt.Sprintf("%s (%d days left)", cur.NotAfter.UTC().Format("2006-01-02 15:04 MST"), cur.DaysLeft)
		if cur.DaysLeft < 0 {
			valid = cur.NotAfter.UTC().Format("2006-01-02 15:04 MST") + " (EXPIRED)"
		}
	}
	s.kv("Valid until", valid)
	s.kv("Fingerprint", colonFP(cur.Fingerprint))
	if cur.PublicCA {
		s.kv("Trust", "a public CA signed it: clients verify it with their roots and pin nothing")
	} else {
		s.kv("Trust", "no public CA signed it: clients pin the fingerprint")
	}
	if st.Listener {
		s.kv("Listener", fmt.Sprintf("port %d", st.Port))
	} else {
		s.kv("Listener", "none (listen.https.address of jailopsd.yaml is empty)")
	}
	if ac := st.ACME; ac != nil {
		s.section("ACME")
		s.kv("State", dash(ac.State))
		s.kv("Domains", joinOrDash(ac.Spec.Domains))
		s.kv("Challenge", fmt.Sprintf("%s (port %d, redirected to %d)", dash(string(ac.Spec.Challenge)), api.ACMEChallengePort(ac.Spec.Challenge), ac.ChallengePort))
		if ac.Spec.DirectoryURL == api.ACMEDirectoryStaging {
			s.kv("Directory", "staging (untrusted certificates, for trying the setup)")
		} else if ac.Spec.DirectoryURL != "" && ac.Spec.DirectoryURL != api.ACMEDirectoryProduction {
			s.kv("Directory", ac.Spec.DirectoryURL)
		}
		if ac.LastError != "" {
			s.kv("Last error", fmt.Sprintf("%s (%d failures in a row)", ac.LastError, ac.Failures))
		}
		if ac.NextAttempt != nil {
			s.kv("Next try", when(ac.NextAttempt))
		}
		if ac.RenewAt != nil {
			s.kv("Renews", when(ac.RenewAt))
		}
		if ac.TermsURL != "" {
			s.kv("Terms", ac.TermsURL)
		}
	}
	if r := st.Redirect; r != nil {
		switch {
		case r.Managed && r.Applied:
			s.kv("Redirect", "applied by the host firewall")
		case r.Managed:
			s.kv("Redirect", "not applied yet: apply the host firewall again ('jailops host firewall set')")
		default:
			fprintln(w, "  Redirect:    add these lines to the translation section of /etc/pf.conf:")
			for _, l := range r.Lines {
				fprintln(w, "      "+l)
			}
		}
	}
	if len(st.Warnings) > 0 {
		s.section("Warnings")
		for _, wn := range st.Warnings {
			fprintln(w, "  "+wn)
		}
	}
	if st.RemoteAdd != "" {
		s.section("Clients add this host with an API token (jot_..., on standard input):")
		fprintln(w, "  "+st.RemoteAdd)
		if !cur.PublicCA && st.Port != 0 && len(cur.Names) > 0 {
			fprintln(w, "or with a single-use trust token from 'jailops trust add' (it pins this certificate):")
			fprintf(w, "  jailops remote add %s:%d --token-stdin\n", cur.Names[0], st.Port)
		}
	}
}

func (a *app) hostCertShow() *cobra.Command {
	return &cobra.Command{
		Use:   "show",
		Short: "Show the certificate the console and the API serve",
		Long: `Show the certificate the TLS listener serves: its subject, names, issuer, expiry
and fingerprint, where it comes from (self-signed, uploaded, ACME or configured),
the state of ACME, and the exact 'jailops remote add' command clients use: without
a fingerprint for a certificate a public CA signed (it is renewed, so it must not
be pinned), with the fingerprint otherwise.`,
		Example: "jailops host certificate show\njailops host certificate show -o json",
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			c, err := a.connect(cmd.Context())
			if err != nil {
				return err
			}
			st, err := c.HostSystem().Certificate().Get(cmd.Context())
			if err != nil {
				return err
			}
			if a.format != fmtTable {
				return a.emit(st, nil, nil, func() []string { return []string{st.Current.Fingerprint} })
			}
			a.printCertificate(a.env.Stdout, st)
			return nil
		},
	}
}

func (a *app) hostCertACME() *cobra.Command {
	var spec api.ACMESpec
	var challenge, directory string
	var staging bool
	cmd := &cobra.Command{
		Use:   "acme --domain NAME... --accept-tos [--email ADDRESS]",
		Short: "Obtain and renew the certificate from a public CA with ACME",
		Long: `Turn ACME on: the daemon obtains a certificate for the names from a public CA
(the production directory of the default CA unless --staging or --directory) and
renews it 30 days before it expires. Every name must point at this host from the
internet; addresses and wildcard names are refused (there is no dns-01).

The CA checks the names with a challenge: http-01 (the default) on port 80, or
tls-alpn-01 on port 443. The daemon is not root, so the host redirects that port
to it: with the host firewall module apply the host firewall once more, otherwise
add the two lines 'show' prints to /etc/pf.conf. --accept-tos says you agree to
the CA's terms of service; 'show' prints their address after the first request.
--staging tries the setup against the staging directory first (its certificates
are not trusted). The answer comes before the CA does: follow it with 'show'.
It needs a global administrator; --dry-run checks the setting and sends nothing.`,
		Example: `jailops host certificate acme --domain console.example.com --email admin@example.com --accept-tos
jailops host certificate acme --domain console.example.com --challenge tls-alpn-01 --accept-tos --staging
jailops host certificate acme --domain console.example.com --accept-tos --dry-run`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if len(spec.Domains) == 0 {
				return usagef("name the certificate's DNS names with --domain (repeatable)")
			}
			if !spec.AcceptTOS {
				return usagef("ACME needs your agreement to the CA's terms of service: read them, then pass --accept-tos")
			}
			if staging && directory != "" {
				return usagef("--staging and --directory exclude each other")
			}
			spec.Enabled, spec.Challenge = true, api.ACMEChallenge(challenge)
			switch {
			case staging:
				spec.DirectoryURL = api.ACMEDirectoryStaging
			case directory != "":
				spec.DirectoryURL = directory
			}
			if err := spec.Validate(); err != nil {
				return err
			}
			if ok, err := a.dry("turn ACME on for the console's certificate", spec.Canonical()); ok || err != nil {
				return err
			}
			c, err := a.connect(cmd.Context())
			if err != nil {
				return err
			}
			st, err := c.HostSystem().Certificate().UseACME(cmd.Context(), spec)
			if err != nil {
				return err
			}
			if a.format != fmtTable {
				return a.emit(st, nil, nil, func() []string { return []string{string(st.Source)} })
			}
			a.say("host-certificate/acme requested for %s; the self-signed certificate is served until the CA answers\n", strings.Join(spec.Domains, ", "))
			if r := st.Redirect; r != nil && !r.Managed && len(r.Lines) > 0 {
				fprintln(a.env.Stderr, "The CA reaches the daemon only through a redirect: add these lines to the translation section of /etc/pf.conf:")
				for _, l := range r.Lines {
					fprintln(a.env.Stderr, "    "+l)
				}
			} else if r != nil && r.Managed && !r.Applied {
				fprintln(a.env.Stderr, "Apply the host firewall once more so that it redirects the challenge port ('jailops host firewall set').")
			}
			fprintln(a.env.Stderr, "Follow the request with: jailops host certificate show")
			return nil
		},
	}
	f := cmd.Flags()
	f.StringSliceVar(&spec.Domains, "domain", nil, "DNS name of the certificate (repeatable, or comma separated; at most 20)")
	f.StringVar(&spec.Email, "email", "", "contact address of the ACME account (optional)")
	f.StringVar(&challenge, "challenge", string(api.ACMEHTTP01), "how the CA checks the names: http-01 (port 80) or tls-alpn-01 (port 443)")
	f.BoolVar(&staging, "staging", false, "use the CA's staging directory (untrusted certificates, generous limits)")
	f.StringVar(&directory, "directory", "", "the ACME directory URL of another CA (https)")
	f.BoolVar(&spec.AcceptTOS, "accept-tos", false, "agree to the CA's terms of service (required)")
	enumFlag(cmd, "challenge", string(api.ACMEHTTP01), string(api.ACMETLSALPN01))
	return cmd
}

func (a *app) hostCertUpload() *cobra.Command {
	var certFile, keyFile, hostname string
	cmd := &cobra.Command{
		Use:   "upload --cert FILE --key FILE [--hostname NAME]",
		Short: "Serve a certificate and key of your own",
		Long: `Upload a PEM certificate chain (the leaf first, then the intermediates) and its
PEM private key. The server checks them before anything is written: the chain is
signed link by link, the key belongs to the leaf and is not encrypted, the leaf
is valid now, for server authentication, and for the host name clients use
(--hostname, default the first DNS name of the leaf). Nothing renews an uploaded
certificate: upload the next one before it expires ('jailops doctor' warns 14
days before). One of the files may be - for standard input. It needs a global
administrator; --dry-run checks the files and sends nothing.`,
		Example: `jailops host certificate upload --cert fullchain.pem --key privkey.pem
jailops host certificate upload --cert fullchain.pem --key privkey.pem --hostname console.example.org`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if certFile == "" || keyFile == "" {
				return usagef("give the certificate chain with --cert FILE and its key with --key FILE")
			}
			if certFile == "-" && keyFile == "-" {
				return usagef("only one of --cert and --key can be standard input")
			}
			chain, err := a.readInput(certFile)
			if err != nil {
				return usagef("reading the certificate: %v", err)
			}
			key, err := a.readInput(keyFile)
			if err != nil {
				return usagef("reading the key: %v", err)
			}
			if len(chain)+len(key) > api.MaxCertificatePEM {
				return usagef("the certificate and the key are larger than %d KiB together", api.MaxCertificatePEM>>10)
			}
			blk, _ := pem.Decode(chain)
			if blk == nil || blk.Type != "CERTIFICATE" {
				return usagef("%s holds no PEM certificate", certFile)
			}
			leaf, err := x509.ParseCertificate(blk.Bytes)
			if err != nil {
				return usagef("%s: %v", certFile, err)
			}
			if hostname == "" {
				switch {
				case len(leaf.DNSNames) > 0:
					hostname = leaf.DNSNames[0]
				case len(leaf.IPAddresses) > 0:
					hostname = leaf.IPAddresses[0].String()
				default:
					return usagef("the certificate names no host: give --hostname")
				}
			}
			in := api.HostCertificateUpload{Certificate: string(chain), Key: string(key), Hostname: hostname}
			shown := map[string]string{"subject": leaf.Subject.String(), "issuer": leaf.Issuer.String(), "hostname": hostname,
				"not_after": leaf.NotAfter.UTC().Format(time.RFC3339)}
			if ok, err := a.dry("upload the console's certificate", shown); ok || err != nil {
				return err
			}
			c, err := a.connect(cmd.Context())
			if err != nil {
				return err
			}
			st, err := c.HostSystem().Certificate().Upload(cmd.Context(), in)
			if err != nil {
				return err
			}
			if a.format != fmtTable {
				return a.emit(st, nil, nil, func() []string { return []string{st.Current.Fingerprint} })
			}
			a.say("host-certificate/uploaded for %s, valid until %s\n", hostname, st.Current.NotAfter.UTC().Format("2006-01-02"))
			if st.RemoteAdd != "" {
				fprintln(a.env.Stderr, "Clients add this host with: "+st.RemoteAdd)
			}
			return nil
		},
	}
	f := cmd.Flags()
	f.StringVar(&certFile, "cert", "", "PEM certificate chain, the leaf first (required)")
	f.StringVar(&keyFile, "key", "", "PEM private key of the leaf, not encrypted (required)")
	f.StringVar(&hostname, "hostname", "", "the name clients use; the certificate must be valid for it (default: its first DNS name)")
	_ = cmd.MarkFlagFilename("cert", "pem", "crt")
	_ = cmd.MarkFlagFilename("key", "pem", "key")
	return cmd
}

func (a *app) hostCertSelfSigned() *cobra.Command {
	var iKnow bool
	cmd := &cobra.Command{
		Use:   "self-signed",
		Short: "Serve the daemon's self-signed certificate again",
		Long: `Go back to the certificate the daemon generated. Browsers warn again, and every
client has to pin its fingerprint: a client that trusted an uploaded or ACME
certificate through its roots stops trusting this host. So when another
certificate is served the command shows it and asks you to type its first name;
--i-know answers that for a script (-y does not). It needs a global
administrator.`,
		Example: "jailops host certificate self-signed\njailops host certificate self-signed --i-know",
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			c, err := a.connect(cmd.Context())
			if err != nil {
				return err
			}
			cur, err := c.HostSystem().Certificate().Get(cmd.Context())
			if err != nil {
				return err
			}
			if cur.Source == api.CertSourceSelfSigned && !cur.Stored {
				a.say("host-certificate/self-signed already served, nothing to do\n")
				return nil
			}
			if ok, err := a.dry("serve the self-signed certificate instead of the "+string(cur.Source)+" one", nil); ok || err != nil {
				return err
			}
			if cur.Source != api.CertSourceSelfSigned {
				name := "self-signed"
				if len(cur.Current.Names) > 0 {
					name = cur.Current.Names[0]
				}
				warn := fmt.Sprintf("This replaces the %s certificate for %s (valid until %s) with the self-signed one:\nbrowsers warn again and every client has to pin the new fingerprint.",
					cur.Source, joinOrDash(cur.Current.Names), cur.Current.NotAfter.UTC().Format("2006-01-02"))
				if err := a.confirmTyped(warn, name, iKnow, "--i-know"); err != nil {
					return err
				}
			}
			st, err := c.HostSystem().Certificate().UseSelfSigned(cmd.Context())
			if err != nil {
				return err
			}
			if a.format != fmtTable {
				return a.emit(st, nil, nil, func() []string { return []string{st.Current.Fingerprint} })
			}
			a.say("host-certificate/self-signed served, fingerprint %s\n", colonFP(st.Current.Fingerprint))
			return nil
		},
	}
	cmd.Flags().BoolVar(&iKnow, "i-know", false, "replace a public or uploaded certificate without typing its name")
	return cmd
}
