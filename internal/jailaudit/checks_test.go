// The jail parameters are read from jail.conf as JailOps renders it; a ruleset JailOps made for the jail's devices
// passes.
func TestJailParams(t *testing.T) {
	p := ParseJailConf("x {\n\tdevfs_ruleset = 5123;\n\tenforce_statfs = 1;\n\tsecurelevel = 3;\n\tallow.mount.zfs;\n\tallow.mount;\n\tallow.mount;\n\tzfs.dataset = \"a/b\";\n}\n")
	if !p.Read || p.EnforceStatfs != 1 || p.SecureLevel == nil || *p.SecureLevel != 3 || p.DevfsRuleset != 5123 || !slices.Equal(p.Allow, []string{"mount", "mount.zfs"}) {
		t.Fatalf("%+v", p)
	}
	in := freshJail()
	in.Params, in.DevfsOwn = p, 5123
	got := results(in, true)
	if got["jail.devfs_ruleset"].Result != api.AuditPass || got["jail.securelevel"].Result != api.AuditPass || got["jail.enforce_statfs"].Result != api.AuditWarn {
		t.Fatalf("%+v", got)
	}
	in.Params = JailParams{Err: "no such file"}
	if c := results(in, false)["jail.enforce_statfs"]; c.Result != api.AuditInfo || !strings.HasPrefix(c.Detail, "not checked") {
		t.Fatalf("unread: %+v", c)
	}
}

// pkg audit's report as pkg 2.9 prints it: the CVE ids of each advisory, the VuXML id of one without.
func TestParsePkgAudit(t *testing.T) {
	out := `pkg: warning: something
python312-3.12.16 is vulnerable:
  Python -- poplib module, when passed a user-controlled command, can have additional commands injected using newlines
  CVE: CVE-2025-15367
  WWW: https://vuxml.FreeBSD.org/freebsd/6d3488ae-2e0f-11f1-88c7-00a098b42aeb.html

  Python -- imaplib module
  CVE: CVE-2025-15366
  CVE: CVE-2025-15365
  WWW: https://vuxml.FreeBSD.org/freebsd/0be929a5-2e0f-11f1-88c7-00a098b42aeb.html

php-pear-Horde_x-1.2_1,1 is vulnerable:
  Horde -- no CVE
  WWW: https://vuxml.FreeBSD.org/freebsd/aaaa-bbbb.html

4 problem(s) in 2 package(s) found.
`
	got := ParsePkgAudit(out)
	if len(got) != 2 || got[0].Name != "python312" || got[0].Version != "3.12.16" || !slices.Equal(got[0].IDs, []string{"CVE-2025-15367", "CVE-2025-15366", "CVE-2025-15365"}) ||
		got[1].Name != "php-pear-Horde_x" || got[1].Version != "1.2_1,1" || !slices.Equal(got[1].IDs, []string{"aaaa-bbbb"}) {
		t.Fatalf("%+v", got)
	}
	if ParsePkgAudit("0 problem(s) in 0 package(s) found.\n") != nil {
		t.Fatal("a clean report names a package")
	}
}

