// The host's vulnerability database: missing is not checked (no failure), older than a week asks for pkg audit -F, a
// vulnerable package warns and is never critical.
func TestVulnerabilities(t *testing.T) {
	in := freshJail()
	in.Vulns = VulnAudit{NotRun: "the host has no vulnerability database (/var/db/pkg/vuln.xml)"}
	if c := results(in, false)["pkg.vulnerabilities"]; c.Result != api.AuditInfo || !strings.Contains(c.Fix, "pkg audit -F on the host") {
		t.Fatalf("missing: %+v", c)
	}
	in.Vulns = VulnAudit{DBDays: 9}
	if c := results(in, false)["pkg.vulnerabilities"]; c.Result != api.AuditInfo || !strings.Contains(c.Detail, "9 days old") || !strings.Contains(c.Fix, "pkg audit -F") {
		t.Fatalf("old: %+v", c)
	}
	in.Vulns = VulnAudit{DBDays: 9, Packages: []VulnPackage{{Name: "curl", Version: "8.1.0", IDs: []string{"CVE-2023-1"}}}}
	if c := results(in, false)["pkg.vulnerabilities"]; c.Result != api.AuditWarn || !strings.Contains(c.Detail, "curl-8.1.0 (CVE-2023-1)") || !strings.Contains(c.Detail, "not current") {
		t.Fatalf("vulnerable: %+v", c)
	}
}

