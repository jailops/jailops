// Only a security check is ever critical, every finding names its fix, and no fix uses sysrc.
func TestEveryFindingHasAFixAndOnlySecurityIsCritical(t *testing.T) {
	got := results(worstJail(), true)
	want := map[string]api.JailAuditResult{"root.links": api.AuditCritical, "accounts.uid0": api.AuditCritical, "accounts.passwords": api.AuditWarn,
		"files.setid": api.AuditWarn, "files.sticky_bit": api.AuditWarn, "files.world_writable": api.AuditWarn, "files.unowned": api.AuditWarn,
		"pkg.repositories": api.AuditWarn, "pkg.base_repository": api.AuditWarn, "pkg.kmods_repository": api.AuditWarn, "pkg.vulnerabilities": api.AuditWarn, "base.updates": api.AuditWarn,
		"base.checksums": api.AuditWarn, "sshd.config": api.AuditWarn, "jail.enforce_statfs": api.AuditWarn,
		"accounts.root_locked": api.AuditInfo, "periodic.world_kernel": api.AuditInfo, "periodic.output": api.AuditInfo, "cron.jitter": api.AuditInfo,
		"rc.conf": api.AuditInfo, "shell.prompt": api.AuditInfo, "hosts.block": api.AuditInfo, "volumes.nosuid": api.AuditInfo,
		"disk.limit": api.AuditInfo, "jail.securelevel": api.AuditInfo, "jail.allow": api.AuditInfo, "jail.devfs_ruleset": api.AuditInfo}
	for id, r := range want {
		c := got[id]
		if c.Result != r {
			t.Errorf("%s: %s, want %s (%s)", id, c.Result, r, c.Detail)
		}
		if c.Fix == "" {
			t.Errorf("%s has no fix", id)
		}
		if strings.Contains(c.Fix, "sysrc") {
			t.Errorf("%s: the fix uses sysrc: %s", id, c.Fix)
		}
		if c.Result == api.AuditCritical && c.Group != GroupSecurity {
			t.Errorf("%s is a practice check and critical", id)
		}
	}
	if len(got) != len(want)+1 { // disk.size is a note without a fix
		t.Errorf("%d checks, want %d", len(got), len(want)+1)
	}
	for id, sub := range map[string]string{"pkg.repositories": "FreeBSD-ports (http://mirror.example.org/x, in /usr/local/etc/pkg/repos/FreeBSD.conf)",
		"rc.conf": `dumpdev="AUTO", ntpd_enable="YES"`, "sshd.config": "PermitRootLogin yes and PasswordAuthentication yes",
		"accounts.passwords": "root, guest", "accounts.root_locked": "toor take a password", "files.unowned": "/srv/old (uid 1234)",
		"pkg.vulnerabilities": "sudo-1.9.1 (CVE-1, CVE-2, CVE-3, CVE-4, CVE-5 and 1 more)", "jail.enforce_statfs": "zfs_delegation",
		"jail.allow": "allow.mount, allow.mount.zfs", "base.updates": "3 newer base packages"} {
		if !strings.Contains(got[id].Detail, sub) {
			t.Errorf("%s: %q lacks %q", id, got[id].Detail, sub)
		}
	}
	if strings.Contains(got["rc.conf"].Detail, "powerd") {
		t.Errorf("powerd_enable=NO named: %s", got["rc.conf"].Detail)
	}
	if !strings.Contains(got["cron.jitter"].Fix, `cron_flags="-J 60" in /etc/rc.conf`) || !strings.Contains(got["cron.jitter"].Fix, "jailops exec web -- service cron restart") {
		t.Errorf("cron fix: %s", got["cron.jitter"].Fix)
	}
}

