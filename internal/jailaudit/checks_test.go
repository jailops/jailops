// freshJail is what the helper reads from a jail of a current image: the defaults of the image, the JailOps block of
// /etc/hosts, the prompt in /root/.shrc; pkg audit names nothing, the last update check found the base current, and
// jail.conf is the one JailOps renders.
func freshJail() Input {
	return Input{
		Jail: "web",
		Facts: Facts{
			Accounts:   Accounts{Read: true, Root: PassLocked, Toor: PassLocked, RootShell: "/bin/sh"},
			ShrcPrompt: true,
			Verified:   1200,
			OwnersRead: true,
			Texts: map[string]string{
				"/etc/rc.conf":       "sendmail_enable=\"NONE\"\nsyslogd_flags=\"-ss\"\ncron_flags=\"-J 60\"\n",
				"/etc/rc.conf.local": "hostname=\"web\"\n",
				"/etc/periodic.conf": "daily_status_world_kernel=\"NO\"\ndaily_output=\"/var/log/daily.log\"\nweekly_output=\"/var/log/weekly.log\"\nmonthly_output=\"/var/log/monthly.log\"\ndaily_status_security_output=\"/var/log/security\"\n",
				"/etc/hosts":         "127.0.0.1 localhost\n# BEGIN JailOps (the name of this jail and its addresses; edit outside this block)\n10.0.0.5\tweb\n# END JailOps\n",
				// FreeBSD 16 ships FreeBSD-base enabled in /etc/pkg; the file of the image turns it off
				"/etc/pkg/FreeBSD.conf": `FreeBSD-ports: {
  url: "pkg+https://pkg.FreeBSD.org/${ABI}/quarterly",
  mirror_type: "srv",
  enabled: yes
}
FreeBSD-base: {
  url: "pkg+https://pkg.FreeBSD.org/${ABI}/base_latest",
  enabled: yes
}
`,
				"/usr/local/etc/pkg/repos/FreeBSD-base.conf": "# Written by JailOps\nFreeBSD-base: { enabled: no }\n",
				"/usr/local/etc/pkg/repos/FreeBSD.conf":      "FreeBSD-ports-kmods: { enabled: no }\n",
				"/usr/local/etc/pkg/repos/jailops.conf":      "jailops: {\n  url: \"https://pkg.example.net/jailops\",\n  signature_type: \"pubkey\"\n}\n",
			},
		},
		HasPkgDB: true, Packages: 52, BasePackages: 50, UsedBytes: 70 << 20, DiskLimit: "10G", Running: true,
		Hostname: "web", Addresses: []string{"10.0.0.5"},
		Vulns:       VulnAudit{DBDays: 1},
		BaseUpdates: BaseUpdates{Checked: true, At: time.Date(2026, 11, 24, 3, 0, 0, 0, time.UTC)},
		Params:      ParseJailConf(renderedConf),
	}
}

// renderedConf is a jail.conf as JailOps renders it for a jail without devices or delegation.
const renderedConf = `# Generated by JailOps
web {
	path = "/jails/web/root";
	host.hostname = "web";
	vnet;
	devfs_ruleset = 4;
	mount.devfs;
	exec.start = "/bin/sh /etc/rc";
	enforce_statfs = 2;
}
`

func results(in Input, suggest bool) map[string]api.JailAuditCheck {
	out := map[string]api.JailAuditCheck{}
	for _, c := range Evaluate(in, suggest) {
		out[c.ID] = c
	}
	return out
}

// A fresh jail passes every default check; with suggest only the notes that describe it (its size, its securelevel)
// are INFO.
func TestFreshJailPasses(t *testing.T) {
	for id, c := range results(freshJail(), false) {
		if c.Result != api.AuditPass || c.Fix != "" || c.Suggestion {
			t.Errorf("%s: %+v", id, c)
		}
	}
	for id, c := range results(freshJail(), true) {
		want := api.AuditPass
		if id == "disk.size" || id == "jail.securelevel" {
			want = api.AuditInfo
		}
		if c.Result != want {
			t.Errorf("suggest %s: %s %s", id, c.Result, c.Detail)
		}
	}
}

// The default checks are PASS, WARN or CRITICAL, or INFO that says it could not check; the suggestions come only with
// suggest, are marked, and are PASS or INFO.
func TestDefaultChecksAndSuggestions(t *testing.T) {
	def := results(freshJail(), false)
	all := results(freshJail(), true)
	for _, id := range []string{"periodic.output", "cron.jitter", "disk.limit", "disk.size", "hosts.block", "volumes.nosuid", "jail.securelevel", "jail.allow", "jail.devfs_ruleset", "accounts.root_locked", "rc.conf", "shell.prompt", "periodic.world_kernel"} {
		if _, ok := def[id]; ok {
			t.Errorf("%s is a default check", id)
		}
		if c, ok := all[id]; !ok || !c.Suggestion || c.Group != GroupPractice {
			t.Errorf("%s: %+v", id, c)
		}
	}
	if _, ok := all["ports.listening"]; ok {
		t.Error("ports.listening is checked")
	}
	for _, in := range []Input{worstJail(), {Jail: "x"}} {
		for _, c := range Evaluate(in, true) {
			switch {
			case c.Suggestion && c.Result != api.AuditPass && c.Result != api.AuditInfo:
				t.Errorf("suggestion %s: %s", c.ID, c.Result)
			case !c.Suggestion && c.Result == api.AuditInfo && !strings.HasPrefix(c.Detail, "not checked: ") && c.ID != "pkg.vulnerabilities":
				t.Errorf("default %s is INFO: %s", c.ID, c.Detail)
			}
		}
	}
}

