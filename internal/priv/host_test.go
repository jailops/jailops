func TestHostIdentityApplyNeedsAdminAndModule(t *testing.T) {
	e, _ := newHostEnv(t)
	c := hostWire(t, e)
	if _, err := c.HostIdentityApply(context.Background(), goodSpec(), true); !api.IsCode(err, api.CodeForbidden) {
		t.Errorf("without the assertion: %v", err)
	}
	_, err := c.HostIdentityApply(admin(), goodSpec(), true)
	var ae *api.Error
	if !asAPIError(err, &ae) || ae.Code != api.CodeForbidden || ae.Detail["module"] != "identity" || !strings.Contains(ae.Hint, "host-manage = identity") {
		t.Errorf("module not in priv.conf: %v", err)
	}
	if _, err := c.HostSnapshotRestore(admin(), "latest", true); !api.IsCode(err, api.CodeForbidden) {
		t.Errorf("restore without the module: %v", err)
	}
	if readFile(t, filepath.Join(e.base, "etc", "resolv.conf")) != origResolv {
		t.Error("a refused request changed a file")
	}
	if _, err := (Config{StateDir: "/x", HostManage: []string{"network"}}).Normalize(); err == nil {
		t.Error("an unknown module was accepted")
	}
	if _, err := (Config{StateDir: "/x", HostManage: []string{"identity", "identity"}}).Normalize(); err == nil {
		t.Error("a module listed twice was accepted")
	}
	if _, err := (Config{StateDir: "/x", HostDir: "relative"}).Normalize(); err == nil {
		t.Error("a relative host-dir was accepted")
	}
}

// Every field is refused when it could carry more than one value into a file: newlines, spaces, options, bad
// addresses and names, duplicates and too many entries. The refusals happen in the helper, over the wire.
func TestHostIdentityRefusals(t *testing.T) {
	e, _ := newHostEnv(t, "identity")
	c := hostWire(t, e)
	long := strings.Repeat("a", 63)
	cases := map[string]api.HostIdentitySpec{
		"empty":                {},
		"hostname newline":     {Hostname: "web\nifconfig_em0=up"},
		"hostname space":       {Hostname: "web example"},
		"hostname quote":       {Hostname: `web"; reboot`},
		"hostname dollar":      {Hostname: "$(reboot)"},
		"hostname leading -":   {Hostname: "-web"},
		"hostname trailing -":  {Hostname: "web-"},
		"hostname label 64":    {Hostname: long + "a.example.org"},
		"hostname too long":    {Hostname: strings.Join([]string{long, long, long, long}, ".")},
		"hostname empty label": {Hostname: "web..example.org"},
		"hostname trailing .":  {Hostname: "web.example.org."},
		"hostname underscore":  {Hostname: "web_1"},
		"hostname is an IP":    {Hostname: "192.0.2.1"},
		"hostname is IPv6":     {Hostname: "2001:db8::1"},
		"no nameserver":        {Resolvers: &api.HostResolvers{}},
		"four nameservers":     {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1", "192.0.2.2", "192.0.2.3", "192.0.2.4"}}},
		"nameserver name":      {Resolvers: &api.HostResolvers{Nameservers: []string{"ns.example.org"}}},
		"nameserver octet":     {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.300"}}},
		"nameserver newline":   {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1\nnameserver 198.51.100.66"}}},
		"nameserver zone":      {Resolvers: &api.HostResolvers{Nameservers: []string{"2001:db8::1%em0"}}},
		"nameserver any4":      {Resolvers: &api.HostResolvers{Nameservers: []string{"0.0.0.0"}}},
		"nameserver any6":      {Resolvers: &api.HostResolvers{Nameservers: []string{"::"}}},
		"nameserver mapped":    {Resolvers: &api.HostResolvers{Nameservers: []string{"::ffff:192.0.2.1"}}},
		"nameserver prefix":    {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.0/24"}}},
		"nameserver duplicate": {Resolvers: &api.HostResolvers{Nameservers: []string{"2001:db8::53", "2001:0db8:0::53"}}},
		"seven search":         {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1"}, Search: []string{"a.example", "b.example", "c.example", "d.example", "e.example", "f.example", "g.example"}}},
		"search space":         {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1"}, Search: []string{"example.org options ndots:15"}}},
		"search newline":       {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1"}, Search: []string{"example.org\nnameserver 198.51.100.66"}}},
		"search duplicate":     {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1"}, Search: []string{"example.org", "EXAMPLE.org"}}},
		"search too long":      {Resolvers: &api.HostResolvers{Nameservers: []string{"192.0.2.1"}, Search: []string{long + "." + long + ".example", long + "." + long + ".example", long + ".example"}}},
		"five ntp":             {NTP: &api.HostNTP{Servers: []string{"a.example", "b.example", "c.example", "d.example", "e.example"}}},
		"ntp newline":          {NTP: &api.HostNTP{Servers: []string{"ntp.example.org\nrestrict default"}}},
		"ntp option":           {NTP: &api.HostNTP{Servers: []string{"-g"}}},
		"ntp space":            {NTP: &api.HostNTP{Servers: []string{"ntp.example.org iburst minpoll 1"}}},
		"ntp zone":             {NTP: &api.HostNTP{Servers: []string{"2001:db8::1%em0"}}},
		"ntp duplicate":        {NTP: &api.HostNTP{Servers: []string{"ntp.example.org", "NTP.example.org"}}},
		"ntp duplicate ip":     {NTP: &api.HostNTP{Servers: []string{"2001:db8::123", "2001:db8:0::123"}}},
	}
	for name, spec := range cases {
		if _, err := c.HostIdentityApply(admin(), spec, true); !api.IsCode(err, api.CodeInvalid) {
			t.Errorf("%s: %v", name, err)
		}
	}
	// the longest valid name passes: three labels of 63 and one of 61, 253 characters
	ok := api.HostIdentitySpec{Hostname: strings.Join([]string{long, long, long, "a" + long[:60]}, ".")}
	if len(ok.Hostname) != 253 {
		t.Fatal(len(ok.Hostname))
	}
	if _, err := c.HostIdentityApply(admin(), ok, true); err != nil {
		t.Errorf("a 253 character name: %v", err)
	}
	if _, err := c.HostSnapshotRestore(admin(), "../../etc", true); !api.IsCode(err, api.CodeInvalid) {
		t.Errorf("snapshot name: %v", err)
	}
	if _, err := c.HostSnapshotRestore(admin(), "20261030T101500Z", true); !api.IsCode(err, api.CodeNotFound) {
		t.Errorf("missing snapshot: %v", err)
	}
	if _, err := c.HostSnapshotRestore(admin(), "latest", true); !api.IsCode(err, api.CodeNotFound) {
		t.Errorf("no snapshot at all: %v", err)
	}
}

