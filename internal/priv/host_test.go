const (
	origResolv = "# Generated by resolvconf\nsearch corp.example.org\nnameserver 198.51.100.1\n"
	origNTP    = "# /etc/ntp.conf\ntos minclock 3 maxclock 6\npool 0.freebsd.pool.ntp.org iburst\nrestrict default limited kod nomodify notrap noquery nopeer\n"
	origRC     = "hostname=\"old.example.org\"\nifconfig_em0=\"DHCP\"\nsshd_enable=\"YES\"\n"
)

// hostSys stands in for the host: hostname(1), sysrc(8), service(8) and ntpq(8) act on the files of etc as the real
// tools would, so a test can check the files afterwards.
type hostSys struct {
	mu       sync.Mutex
	etc      string
	hostname string
	ntpdFail bool
	ntpq     string
	restarts int
}

var reSysrcArg = regexp.MustCompile(`^([a-z_]+)=(.*)$`)

func (h *hostSys) rules(r *run.Fake) {
	r.Add(run.Rule{Name: hostnameBin, Args: []string{run.RestArgs}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		if len(c.Args) == 1 {
			h.hostname = c.Args[0]
			return run.Result{}, nil
		}
		return run.Result{Stdout: []byte(h.hostname + "\n")}, nil
	}})
	r.Add(run.Rule{Name: sysrcBin, Args: []string{"-f", run.AnyArg, run.AnyArg}, Fn: func(c run.Cmd) (run.Result, error) {
		m := reSysrcArg.FindStringSubmatch(c.Args[2])
		b, err := os.ReadFile(c.Args[1])
		if m == nil || err != nil {
			return run.Result{ExitCode: 1}, &run.ExitError{Name: sysrcBin, Code: 1, Stderr: "bad"}
		}
		lines := splitLines(string(b))
		line := m[1] + `="` + m[2] + `"`
		done := false
		for i, l := range lines {
			if strings.HasPrefix(l, m[1]+"=") {
				lines[i], done = line, true
			}
		}
		if !done {
			lines = append(lines, line)
		}
		return run.Result{}, os.WriteFile(c.Args[1], []byte(strings.Join(lines, "\n")+"\n"), 0o644)
	}})
	r.Add(run.Rule{Name: serviceBin, Args: []string{"ntpd", run.AnyArg}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		if h.ntpdFail {
			return run.Result{ExitCode: 1}, &run.ExitError{Name: serviceBin, Code: 1, Stderr: "ntpd: cannot start"}
		}
		h.restarts++
		return run.Result{}, nil
	}})
	r.Add(run.Rule{Name: ntpqBin, Args: []string{"-pn"}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		return run.Result{Stdout: []byte(h.ntpq)}, nil
	}})
}

// newHostEnv is newEnv with an etc directory of its own, a fixed clock and the given modules in host-manage.
func newHostEnv(t *testing.T, modules ...string) (*env, *hostSys) {
	t.Helper()
	e := newEnv(t)
	etc := filepath.Join(e.base, "etc")
	mustWrite(t, filepath.Join(etc, "resolv.conf"), origResolv)
	mustWrite(t, filepath.Join(etc, "ntp.conf"), origNTP)
	mustWrite(t, filepath.Join(etc, "rc.conf"), origRC)
	h := &hostSys{etc: etc, hostname: "old.example.org",
		ntpq: "     remote           refid      st t when poll reach   delay   offset  jitter\n==============================================================================\n*192.0.2.123     .GPS.            1 u   12   64  377    1.234    0.012   0.010\n"}
	h.rules(e.runner)
	var mu sync.Mutex
	clock := time.Date(2026, 10, 30, 10, 15, 0, 0, time.UTC)
	cfg := e.cfg
	cfg.HostManage = modules
	cfg.HostDir = filepath.Join(e.base, "priv", "host")
	l, err := NewLocal(cfg, Deps{ZFS: e.zfs, Jails: e.jails, PF: e.pf, Net: e.net, Runner: e.runner, Jexec: e.jexec, Etc: etc,
		Now: func() time.Time { mu.Lock(); defer mu.Unlock(); clock = clock.Add(time.Second); return clock }}, WithoutChown())
	if err != nil {
		t.Fatal(err)
	}
	e.local, e.cfg = l, l.Config()
	return e, h
}

// hostWire serves the env and returns a client: every call below goes through the protocol and the real rules.
func hostWire(t *testing.T, e *env) *Client {
	t.Helper()
	f := e.serve(t, selfPeers())
	c, err := Dial(f.sock)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { c.Close() })
	return c
}

func readFile(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

