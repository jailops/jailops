// The helper writes neither through a link in /etc nor files a snapshot manifest names outside the module.
func TestHostRefusesLinksAndForeignFiles(t *testing.T) {
	e, _ := newHostEnv(t, "identity")
	c := hostWire(t, e)
	etc := filepath.Join(e.base, "etc")
	target := filepath.Join(e.base, "elsewhere")
	mustWrite(t, target, "nameserver 198.51.100.1\n")
	os.Remove(filepath.Join(etc, "resolv.conf"))
	if err := os.Symlink(target, filepath.Join(etc, "resolv.conf")); err != nil {
		t.Fatal(err)
	}
	if _, err := c.HostIdentityApply(admin(), goodSpec(), false); !api.IsCode(err, api.CodeForbidden) {
		t.Errorf("symlinked resolv.conf: %v", err)
	}
	if readFile(t, target) != "nameserver 198.51.100.1\n" {
		t.Error("written through the link")
	}
	os.Remove(filepath.Join(etc, "resolv.conf"))
	mustWrite(t, filepath.Join(etc, "resolv.conf"), origResolv)
	res, err := c.HostIdentityApply(admin(), api.HostIdentitySpec{Hostname: "web3"}, false)
	if err != nil {
		t.Fatal(err)
	}
	// a manifest that names another file is refused
	man := filepath.Join(e.cfg.HostDir, "snapshots", res.Snapshot, "snapshot.json")
	var m hostManifest
	if err := json.Unmarshal([]byte(readFile(t, man)), &m); err != nil {
		t.Fatal(err)
	}
	m.Files = append(m.Files, hostSnapFile{Name: "master.passwd", Exists: true})
	b, _ := json.Marshal(m)
	mustWrite(t, man, string(b))
	if _, err := c.HostSnapshotRestore(admin(), res.Snapshot, false); !api.IsCode(err, api.CodeForbidden) {
		t.Errorf("foreign file: %v", err)
	}
}

