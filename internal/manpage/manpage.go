// Package manpage writes the man pages of a cobra command tree as mdoc(7), one page per command, the way the
// FreeBSD base system documents its tools. The output is deterministic: commands and flags are sorted, and the
// date comes from SOURCE_DATE_EPOCH when it is set. The packages run the hidden `man DIR` command of the tools at
// build time; nothing generated is committed.
//
// The pages follow the mdoc conventions mandoc -Tlint checks: every sentence starts on an input line of its own,
// no input line is longer than 80 bytes, SEE ALSO is sorted by section and name, and no paragraph macro stands
// where it would be ignored. A literal line (an example) longer than 80 bytes is continued on the next line
// with a trailing backslash, as a shell would read it.
package manpage

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// width is the longest input line mandoc accepts without a remark.
const width = 80

// Write writes the page of root and of every available command below it into dir as <name>.1, with the words of
// the command path joined by dashes (jailops-jail-list.1). seeAlso are references, such as "jailopsd(8)", added
// to the SEE ALSO section of the root page.
func Write(root *cobra.Command, dir string, seeAlso ...string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	date, err := date()
	if err != nil {
		return err
	}
	var walk func(c *cobra.Command, extra []string) error
	walk = func(c *cobra.Command, extra []string) error {
		path := filepath.Join(dir, pageName(c)+".1")
		if err := os.WriteFile(path, []byte(Page(c, date, extra...)), 0o644); err != nil {
			return err
		}
		for _, s := range c.Commands() {
			if s.IsAvailableCommand() {
				if err := walk(s, nil); err != nil {
					return err
				}
			}
		}
		return nil
	}
	return walk(root, seeAlso)
}

// date is the .Dd line: SOURCE_DATE_EPOCH for a reproducible build, else today.
func date() (string, error) {
	now := time.Now()
	if v := os.Getenv("SOURCE_DATE_EPOCH"); v != "" {
		n, err := strconv.ParseInt(v, 10, 64)
		if err != nil {
			return "", fmt.Errorf("SOURCE_DATE_EPOCH: %w", err)
		}
		now = time.Unix(n, 0)
	}
	return now.UTC().Format("January 2, 2006"), nil
}

func pageName(c *cobra.Command) string { return strings.ReplaceAll(c.CommandPath(), " ", "-") }

// page collects the input lines of one page.
type page struct {
	b strings.Builder
}

func (p *page) line(format string, a ...any) { fmt.Fprintf(&p.b, format+"\n", a...) }

func (p *page) lines(ls []string) {
	for _, l := range ls {
		p.b.WriteString(l)
		p.b.WriteByte('\n')
	}
}

// Page renders one command. seeAlso are extra references for its SEE ALSO section.
func Page(c *cobra.Command, date string, seeAlso ...string) string {
	p := &page{}
	name := pageName(c)
	p.line(`.\" generated by: %s man DIR`, c.Root().Name())
	p.line(".Dd %s", date)
	p.line(".Dt %s 1", strings.ToUpper(name))
	p.line(".Os")
	p.line(".Sh NAME")
	p.line(".Nm %s", name)
	// the text of a long one-line description continues on plain text lines inside the Nd block
	p.lines(macroWrap(".Nd ", "", arg(c.Short)))
	p.line(".Sh SYNOPSIS")
	p.line(".Nm %s", c.CommandPath())
	if rest := strings.TrimSpace(strings.TrimPrefix(c.UseLine(), c.CommandPath())); rest != "" {
		p.lines(macroWrap(".Ar ", ".Ar ", arg(rest)))
	}
	p.line(".Sh DESCRIPTION")
	long := c.Long
	if long == "" {
		long = c.Short
	}
	paragraphs(p, long)
	if len(c.Aliases) > 0 {
		p.line(".Pp")
		p.lines(textLines("Also called " + strings.Join(c.Aliases, ", ") + "."))
	}
	var subs []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() {
			subs = append(subs, s)
		}
	}
	if len(subs) > 0 {
		p.line(".Sh COMMANDS")
		p.line(".Bl -tag -width Ds")
		for _, s := range subs {
			p.line(".It Cm %s", arg(s.Name()))
			p.lines(textLines(s.Short))
			p.line("See")
			p.line(".Xr %s 1 .", pageName(s))
		}
		p.line(".El")
	}
	flags(p, "OPTIONS", c.NonInheritedFlags())
	flags(p, "GLOBAL OPTIONS", c.InheritedFlags())
	if c.Example != "" {
		p.line(".Sh EXAMPLES")
		p.line(".Bd -literal -offset indent")
		for _, l := range strings.Split(strings.TrimRight(c.Example, "\n"), "\n") {
			p.lines(literal(l))
		}
		p.line(".Ed")
	}
	var refs []string
	if parent := c.Parent(); parent != nil {
		refs = append(refs, pageName(parent)+"(1)")
	}
	for _, s := range subs {
		refs = append(refs, pageName(s)+"(1)")
	}
	refs = append(refs, seeAlso...)
	if len(refs) > 0 {
		p.line(".Sh SEE ALSO")
		xrs := make([][2]string, 0, len(refs))
		for _, r := range refs {
			name, section := r, "1"
			if open := strings.Index(r, "("); open > 0 && strings.HasSuffix(r, ")") {
				name, section = r[:open], r[open+1:len(r)-1]
			}
			xrs = append(xrs, [2]string{name, section})
		}
		// mdoc lists references by section, then by name
		sort.Slice(xrs, func(i, j int) bool {
			if xrs[i][1] != xrs[j][1] {
				return xrs[i][1] < xrs[j][1]
			}
			return xrs[i][0] < xrs[j][0]
		})
		for i, x := range xrs {
			sep := " ,"
			if i == len(xrs)-1 {
				sep = ""
			}
			p.line(".Xr %s %s%s", x[0], x[1], sep)
		}
	}
	return p.b.String()
}

// paragraphs writes free text: blank lines separate paragraphs, indented lines are shown as they are. A
// paragraph macro is never put right before a display, where it would be ignored.
func paragraphs(p *page, s string) {
	literalBlock := false
	wrote := false   // something of this text was written
	pending := false // a paragraph break waits for the next text line
	for _, l := range strings.Split(strings.TrimRight(s, "\n"), "\n") {
		switch {
		case strings.TrimSpace(l) == "":
			if literalBlock {
				p.line(".Ed")
				literalBlock = false
			}
			pending = wrote
			continue
		case strings.HasPrefix(l, " ") || strings.HasPrefix(l, "\t"):
			if !literalBlock {
				p.line(".Bd -literal -offset indent")
				literalBlock = true
			}
			pending = false
			p.lines(literal(l))
			wrote = true
			continue
		case literalBlock:
			p.line(".Ed")
			literalBlock = false
		}
		if pending {
			p.line(".Pp")
			pending = false
		}
		p.lines(textLines(l))
		wrote = true
	}
	if literalBlock {
		p.line(".Ed")
	}
}

// flags writes one section of flags, sorted by name, hidden and deprecated ones left out.
func flags(p *page, title string, fs *pflag.FlagSet) {
	var items [][]string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Deprecated != "" {
			return
		}
		varname, usage := pflag.UnquoteUsage(f)
		it := ".It "
		if f.Shorthand != "" {
			it += fmt.Sprintf("Fl %s , ", f.Shorthand)
		}
		it += "Fl -" + f.Name
		if varname != "" && f.NoOptDefVal == "" {
			it += " Ar " + arg(varname)
		}
		if !zeroDefault(f) {
			usage += " (default " + f.DefValue + ")"
		}
		items = append(items, append([]string{it}, textLines(usage)...))
	})
	if len(items) == 0 {
		return
	}
	p.line(".Sh %s", title)
	p.line(".Bl -tag -width Ds")
	for _, it := range items {
		p.lines(it)
	}
	p.line(".El")
}

// zeroDefault reports whether the default is not worth printing, the way the usage text of the tools leaves it out.
func zeroDefault(f *pflag.Flag) bool {
	switch f.DefValue {
	case "", "false", "0", "0s", "[]", "<nil>":
		return true
	}
	return false
}

// arg escapes the argument of a macro line: a backslash is written as itself, a double quote must not open
// a quoted argument, and the end-of-options separator stays two hyphens.
func arg(s string) string {
	s = strings.ReplaceAll(s, `\`, `\e`)
	s = strings.ReplaceAll(s, `"`, `\(dq`)
	return strings.Join(dashes(strings.Fields(s)), " ")
}

// dashes writes a word that is just "--" as two literal hyphens, not a dash.
func dashes(words []string) []string {
	for i, w := range words {
		if w == "--" {
			words[i] = `\-\-`
		}
	}
	return words
}

// osWord returns the trailing punctuation of a word that is the operating system's name on its own, and
// whether it is one: that word is written with the Fx macro.
func osWord(w string) (string, bool) {
	rest, ok := strings.CutPrefix(w, "FreeBSD")
	if !ok || strings.Trim(rest, `.,;:!?)`) != "" {
		return "", false
	}
	return rest, true
}

// leading keeps a text line from starting with a control character.
func leading(s string) string {
	if strings.HasPrefix(s, ".") || strings.HasPrefix(s, "'") {
		return `\&` + s
	}
	return s
}

// textLines renders one line of free text as input lines: a backslash written as itself, tabs as spaces,
// every sentence on a line of its own, no line longer than 80 bytes, none starting with a control character.
func textLines(s string) []string {
	s = strings.ReplaceAll(s, `\`, `\e`)
	s = strings.ReplaceAll(s, "\t", "    ")
	var out []string
	for _, sentence := range sentences(s) {
		// the operating system's name is a macro of its own line; the text around it keeps its lines
		var seg []string
		for _, w := range dashes(strings.Fields(sentence)) {
			punct, ok := osWord(w)
			if !ok {
				seg = append(seg, w)
				continue
			}
			out = append(out, wrap(strings.Join(seg, " "))...)
			seg = nil
			fx := ".Fx"
			for _, c := range punct {
				fx += " " + string(c)
			}
			out = append(out, fx)
		}
		out = append(out, wrap(strings.Join(seg, " "))...)
	}
	return out
}

// sentences splits where a formatter wants a new input line: after ".", "!" or "?" (and any closing bracket or
// quote), when blanks and a capital letter follow.
func sentences(s string) []string {
	var out []string
	start := 0
	for i := 0; i < len(s); i++ {
		if s[i] != '.' && s[i] != '!' && s[i] != '?' {
			continue
		}
		j := i + 1
		for j < len(s) && strings.IndexByte(`)]'"`, s[j]) >= 0 {
			j++
		}
		k := j
		for k < len(s) && s[k] == ' ' {
			k++
		}
		if k == j || k >= len(s) || s[k] < 'A' || s[k] > 'Z' {
			continue
		}
		out = append(out, strings.TrimSpace(s[start:j]))
		start, i = k, k-1
	}
	if rest := strings.TrimSpace(s[start:]); rest != "" {
		out = append(out, rest)
	}
	return out
}

// wrap breaks a text line at blanks into lines of at most 80 bytes; a word longer than that stays whole.
func wrap(s string) []string {
	if strings.TrimSpace(s) == "" {
		return nil
	}
	return macroWrap("", "", s)
}

// macroWrap writes a line whose words may not fit: the first line starts with first, the following ones with
// cont (a plain text line when cont is empty).
func macroWrap(first, cont, s string) []string {
	words := strings.Fields(s)
	if len(words) == 0 {
		return []string{strings.TrimSpace(first)}
	}
	line := first + leading(words[0])
	var out []string
	for _, w := range words[1:] {
		if len(line)+1+len(w) > width {
			out = append(out, line)
			line = cont + leading(w)
			continue
		}
		line += " " + w
	}
	return append(out, line)
}

// literal renders one line of a display. A line longer than 80 bytes is continued the way a shell reads it: a
// trailing backslash, and the rest indented on the next line.
func literal(l string) []string {
	l = strings.ReplaceAll(strings.TrimRight(l, " \t"), `\`, `\e`)
	indent := l[:len(l)-len(strings.TrimLeft(l, " \t"))]
	var out []string
	for len(l) > width {
		cut := strings.LastIndexByte(l[:width-2], ' ')
		if cut <= len(indent) {
			break
		}
		out = append(out, leading(strings.TrimRight(l[:cut], " "))+` \e`)
		l = indent + "    " + strings.TrimLeft(l[cut:], " ")
	}
	return append(out, leading(l))
}
