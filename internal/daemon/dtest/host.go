package dtest

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"testing"
	"time"

	"jailops.net/jailops/internal/priv"
	"jailops.net/jailops/internal/sys/run"
)

// Files of the simulated host's etc directory before any change.
const (
	HostResolv = "# Generated by resolvconf\nsearch corp.example.org\nnameserver 198.51.100.1\n"
	HostNTP    = "# /etc/ntp.conf\npool 0.freebsd.pool.ntp.org iburst\n"
	HostRC     = "hostname=\"old.example.org\"\nsshd_enable=\"YES\"\n"
)

// HostSim is the host that host management changes in tests: an etc directory and stand-ins for hostname(1),
// sysrc(8), service(8) and ntpq(8) that act on it, behind a real helper (priv.Local) so every request passes the
// helper's own rules, the admin assertion included.
type HostSim struct {
	Etc   string
	Local *priv.Local
	Run   *run.Fake

	mu       sync.Mutex
	hostname string
	restarts int
	ntpq     string
}

var reSysrc = regexp.MustCompile(`^([a-z_]+)=(.*)$`)

func newHostSim(t testing.TB, dir string, modules []string) *HostSim {
	h := &HostSim{Etc: filepath.Join(dir, "etc"), Run: run.NewFake(), hostname: "old.example.org",
		ntpq: "*192.0.2.123     .GPS.            1 u   12   64  377    1.234    0.012   0.010\n"}
	for n, s := range map[string]string{"resolv.conf": HostResolv, "ntp.conf": HostNTP, "rc.conf": HostRC} {
		if err := os.MkdirAll(h.Etc, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(h.Etc, n), []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	h.Run.Add(run.Rule{Name: "/bin/hostname", Args: []string{run.RestArgs}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		if len(c.Args) == 1 {
			h.hostname = c.Args[0]
			return run.Result{}, nil
		}
		return run.Result{Stdout: []byte(h.hostname + "\n")}, nil
	}})
	h.Run.Add(run.Rule{Name: "/usr/sbin/sysrc", Args: []string{"-f", run.AnyArg, run.AnyArg}, Fn: func(c run.Cmd) (run.Result, error) {
		m := reSysrc.FindStringSubmatch(c.Args[2])
		b, err := os.ReadFile(c.Args[1])
		if m == nil || err != nil {
			return run.Result{ExitCode: 1}, &run.ExitError{Name: c.Name, Code: 1}
		}
		lines := strings.Split(strings.TrimSuffix(string(b), "\n"), "\n")
		line, done := m[1]+`="`+m[2]+`"`, false
		for i, l := range lines {
			if strings.HasPrefix(l, m[1]+"=") {
				lines[i], done = line, true
			}
		}
		if !done {
			lines = append(lines, line)
		}
		return run.Result{}, os.WriteFile(c.Args[1], []byte(strings.Join(lines, "\n")+"\n"), 0o644)
	}})
	h.Run.Add(run.Rule{Name: "/usr/sbin/service", Args: []string{"ntpd", run.AnyArg}, Fn: func(run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		h.restarts++
		return run.Result{}, nil
	}})
	h.Run.Add(run.Rule{Name: "/usr/bin/ntpq", Args: []string{"-pn"}, Fn: func(run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		return run.Result{Stdout: []byte(h.ntpq)}, nil
	}})
	var cmu sync.Mutex
	clock := time.Date(2026, 10, 30, 10, 15, 0, 0, time.UTC)
	cfg := priv.Config{StateDir: filepath.Join(dir, "privstate"), StorageFile: filepath.Join(dir, "priv.d", "storage.conf"),
		HostDir: filepath.Join(dir, "privhost"), HostManage: modules}
	l, err := priv.NewLocal(cfg, priv.Deps{Runner: h.Run, Etc: h.Etc,
		Now: func() time.Time { cmu.Lock(); defer cmu.Unlock(); clock = clock.Add(time.Second); return clock }}, priv.WithoutChown())
	if err != nil {
		t.Fatal(err)
	}
	h.Local = l
	return h
}

// Hostname is the running host name of the simulated host.
func (h *HostSim) Hostname() string { h.mu.Lock(); defer h.mu.Unlock(); return h.hostname }

// NTPRestarts counts the ntpd restarts and stops.
func (h *HostSim) NTPRestarts() int { h.mu.Lock(); defer h.mu.Unlock(); return h.restarts }

// SetNTPQ replaces what ntpq prints.
func (h *HostSim) SetNTPQ(s string) { h.mu.Lock(); defer h.mu.Unlock(); h.ntpq = s }

// File reads a file of the simulated etc directory.
func (h *HostSim) File(name string) string {
	b, _ := os.ReadFile(filepath.Join(h.Etc, name))
	return string(b)
}
