package backupd

import (
	"fmt"
	"io"
	"strings"
)

// The completion scripts are generated from the command table (verbs): the shell learns the commands, their
// subcommands and positional words, and their flags. Nothing is completed from the database or the daemon.

// globalFlags are accepted before and after the command.
var globalFlags = []string{"-c FILE", "--config FILE", "--json", "--help", "--version"}

func (c *cli) completion(args []string) error {
	if len(args) != 1 {
		return fmt.Errorf("completion bash|zsh|fish")
	}
	switch args[0] {
	case "bash":
		return writeBash(c.out)
	case "zsh":
		return writeZsh(c.out)
	case "fish":
		return writeFish(c.out)
	}
	return fmt.Errorf("completion: unknown shell %q (bash, zsh or fish)", args[0])
}

// flagName is "--grace" of "--grace DURATION"; takesValue says whether a value follows; isFile whether that value
// is a file name.
func flagName(f string) (name string, takesValue, isFile bool) {
	name, value, _ := strings.Cut(f, " ")
	return name, value != "", value == "FILE"
}

func names(flags []string) []string {
	var out []string
	for _, f := range flags {
		n, _, _ := flagName(f)
		out = append(out, n)
	}
	return out
}

// fileFlags are the flags, global and of any command, whose value is a file name (each once).
func fileFlags() []string {
	var out []string
	seen := map[string]bool{}
	for _, f := range append(append([]string(nil), globalFlags...), allFlags()...) {
		if n, _, isFile := flagName(f); isFile && !seen[n] {
			seen[n] = true
			out = append(out, n)
		}
	}
	return out
}

func allFlags() []string {
	var out []string
	for _, v := range verbs {
		out = append(out, v.flags...)
	}
	return out
}

// topLevel lists the one-word commands.
func topLevel() []string {
	var out []string
	for _, v := range verbs {
		if !strings.Contains(v.name, " ") {
			out = append(out, v.name)
		}
	}
	return out
}

// candidates are the words the shell offers after the command named name: its positional words and its flags.
func candidates(v verb) string {
	return strings.Join(append(append([]string(nil), v.words...), names(v.flags)...), " ")
}

// The bash and zsh scripts share one shape: find the command (and its subcommand, when the table has a row for
// the pair) among the words typed so far, then offer the words of that row.

func writeBash(w io.Writer) error {
	fmt.Fprintf(w, `# bash completion for jailops-backupd, generated by: jailops-backupd completion bash
_jailops_backupd()
{
	local cur prev verb sub key words i w
	cur=${COMP_WORDS[COMP_CWORD]}
	prev=${COMP_WORDS[COMP_CWORD-1]}
	verb= sub=
	for ((i = 1; i < COMP_CWORD; i++)); do
		w=${COMP_WORDS[i]}
		case $w in
		-c|--config) i=$((i + 1)) ;;
		-*) ;;
		*) if [ -z "$verb" ]; then verb=$w; elif [ -z "$sub" ]; then sub=$w; fi ;;
		esac
	done
	case $prev in
	%s) COMPREPLY=($(compgen -f -- "$cur")); return ;;
	esac
	case "$verb $sub" in
%s	*) key=$verb ;;
	esac
	case $key in
	"") words="%s" ;;
%s	*) words= ;;
	esac
	COMPREPLY=($(compgen -W "$words" -- "$cur"))
}
complete -F _jailops_backupd jailops-backupd
`, strings.Join(fileFlags(), "|"), pairCases(), strings.Join(append(topLevel(), names(globalFlags)...), " "), wordCases())
	return nil
}

func writeZsh(w io.Writer) error {
	fmt.Fprintf(w, `#compdef jailops-backupd
# zsh completion for jailops-backupd, generated by: jailops-backupd completion zsh
_jailops_backupd()
{
	local verb sub key i w
	local -a cands
	verb= sub=
	for ((i = 2; i < CURRENT; i++)); do
		w=$words[i]
		case $w in
		-c|--config) ((i++)) ;;
		-*) ;;
		*) if [[ -z $verb ]]; then verb=$w; elif [[ -z $sub ]]; then sub=$w; fi ;;
		esac
	done
	case $words[CURRENT-1] in
	%s) _files; return ;;
	esac
	case "$verb $sub" in
%s	*) key=$verb ;;
	esac
	case $key in
	"") cands=(%s) ;;
%s	*) cands=() ;;
	esac
	compadd -- $cands
}
_jailops_backupd "$@"
`, strings.Join(fileFlags(), "|"), pairCases(), strings.Join(append(topLevel(), names(globalFlags)...), " "), wordCasesZsh())
	return nil
}

// pairCases maps "verb sub" to the row of the pair, for every two-word row.
func pairCases() string {
	var b strings.Builder
	for _, v := range verbs {
		if strings.Contains(v.name, " ") {
			fmt.Fprintf(&b, "\t%q) key=%q ;;\n", v.name, v.name)
		}
	}
	return b.String()
}

func wordCases() string {
	var b strings.Builder
	for _, v := range verbs {
		fmt.Fprintf(&b, "\t%q) words=%q ;;\n", v.name, candidates(v))
	}
	return b.String()
}

func wordCasesZsh() string {
	var b strings.Builder
	for _, v := range verbs {
		fmt.Fprintf(&b, "\t%q) cands=(%s) ;;\n", v.name, candidates(v))
	}
	return b.String()
}

func writeFish(w io.Writer) error {
	fmt.Fprintln(w, "# fish completion for jailops-backupd, generated by: jailops-backupd completion fish")
	fmt.Fprintln(w, "complete -c jailops-backupd -f")
	fmt.Fprintln(w, "complete -c jailops-backupd -s c -l config -rF -d 'configuration file'")
	fmt.Fprintln(w, "complete -c jailops-backupd -l json -d 'raw answers'")
	fmt.Fprintln(w, "complete -c jailops-backupd -l help -d 'describe a command'")
	fmt.Fprintln(w, "complete -c jailops-backupd -l version -d 'print the version'")
	for _, v := range verbs {
		first, sub, pair := strings.Cut(v.name, " ")
		var cond string
		if pair {
			cond = fmt.Sprintf("__fish_seen_subcommand_from %s; and __fish_seen_subcommand_from %s", first, sub)
		} else {
			cond = "__fish_seen_subcommand_from " + first
			fmt.Fprintf(w, "complete -c jailops-backupd -n __fish_use_subcommand -a %s -d %s\n", first, fishQuote(v.desc))
		}
		if len(v.words) > 0 {
			fmt.Fprintf(w, "complete -c jailops-backupd -n '%s; and not __fish_seen_subcommand_from %s' -a '%s'\n", cond, strings.Join(v.words, " "), strings.Join(v.words, " "))
		}
		for _, f := range v.flags {
			n, takesValue, isFile := flagName(f)
			opt := ""
			if isFile {
				opt = " -rF"
			} else if takesValue {
				opt = " -r"
			}
			fmt.Fprintf(w, "complete -c jailops-backupd -n '%s' -l %s%s\n", cond, strings.TrimPrefix(n, "--"), opt)
		}
	}
	return nil
}

func fishQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", "\\'") + "'" }
