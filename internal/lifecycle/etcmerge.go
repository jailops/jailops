// The /etc merge of a generation switch (upgrade, or root rollback in the
// reverse direction). Verified on FreeBSD 15.1 (prototype 2):
//
//	tar -C <generation root> -cf <old-etc.tar> ./etc            (the baseline)
//	tar -C <generation root> -cf <new-etc.tar> ./etc            (the target)
//	etcupdate extract -d <work> -t <old-etc.tar> -D <jail root>
//	etcupdate -d <work> -t <new-etc.tar> -D <jail root> -L <log>
//
// etcupdate reports "C <path>" for a conflict and "M <path>" for a merged
// file; a non-zero exit with no "C" line is a plain failure. etcupdate hands
// master.passwd and group to a line diff, which conflicts when both sides
// add a user, so those two are merged by key (Merge3Keyed) instead and
// passwd/pwd.db/spwd.db are regenerated by pwd_mkdb. rc.conf is never merged:
// the base does not ship it.

// accountFiles are the files merged by key; etcupdate's opinion of them is
// ignored. The databases are derived from master.passwd.
var accountFiles = map[string]bool{
	"/etc/master.passwd": true, "/etc/passwd": true, "/etc/group": true,
	"/etc/pwd.db": true, "/etc/spwd.db": true,
}

// MergeInput describes one /etc merge.
type MergeInput struct {
	// DestRoot is the current root with the persistent datasets mounted under it.
	DestRoot string
	// OldRoot is the mounted root of the generation the jail runs now: the
	// baseline of the three-way merge.
	OldRoot string
	// NewRoot is the mounted root of the target generation.
	NewRoot string
	// Work is a scratch directory for the tarballs and etcupdate's state.
	Work string
}

// MergeConfig is the merge strategy; the zero value is the verified one.
type MergeConfig struct {
	// Tar, Etcupdate and PwdMkdb name the tools (for hosts that install
	// them elsewhere).
	Tar, Etcupdate, PwdMkdb string
}

// DefaultMerge returns the verified strategy.
func DefaultMerge() MergeConfig {
	return MergeConfig{Tar: "tar", Etcupdate: "etcupdate", PwdMkdb: "pwd_mkdb"}
}

func (c MergeConfig) names() MergeConfig {
	d := DefaultMerge()
	if c.Tar == "" {
		c.Tar = d.Tar
	}
	if c.Etcupdate == "" {
		c.Etcupdate = d.Etcupdate
	}
	if c.PwdMkdb == "" {
		c.PwdMkdb = d.PwdMkdb
	}
	return c
}

// ParseEtcupdate reads the log of etcupdate: conflicting and merged paths.
func ParseEtcupdate(out []byte) (conflicts, merged []string) {
	sc := bufio.NewScanner(bytes.NewReader(out))
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(l, "C "):
			conflicts = append(conflicts, strings.TrimSpace(l[2:]))
		case strings.HasPrefix(l, "M "):
			merged = append(merged, strings.TrimSpace(l[2:]))
		}
	}
	return conflicts, merged
}

// Merge3Result is the outcome of a keyed three-way merge.
type Merge3Result struct {
	Lines     []string
	Conflicts []string // keys
}

// PasswdKey keys master.passwd (and group) lines by name.
func PasswdKey(line string) string {
	if i := strings.IndexByte(line, ':'); i >= 0 && !strings.HasPrefix(line, "#") {
		return line[:i]
	}
	return "\x00" + line
}

// Merge3Keyed merges ours and theirs against base line by key. It never
// guesses: a key changed differently on both sides is a conflict (ours is
// kept in Lines). Comments and blank lines key as themselves.
func Merge3Keyed(base, ours, theirs []string, key func(string) string) Merge3Result {
	idx := func(l []string) (map[string]string, []string) {
		m := map[string]string{}
		var order []string
		for _, x := range l {
			k := key(x)
			if _, ok := m[k]; !ok {
				order = append(order, k)
				m[k] = x
			}
		}
		return m, order
	}
	bm, bo := idx(base)
	om, oo := idx(ours)
	tm, to := idx(theirs)
	var keys []string
	seen := map[string]bool{}
	for _, l := range [][]string{oo, to, bo} {
		for _, k := range l {
			if !seen[k] {
				seen[k] = true
				keys = append(keys, k)
			}
		}
	}
	var r Merge3Result
	for _, k := range keys {
		b, bok := bm[k]
		o, ook := om[k]
		t, tok := tm[k]
		pick := func(v string, ok bool) {
			if ok {
				r.Lines = append(r.Lines, v)
			}
		}
		switch {
		case ook == tok && o == t:
			pick(o, ook)
		case ook == bok && o == b:
			pick(t, tok)
		case tok == bok && t == b:
			pick(o, ook)
		default:
			r.Conflicts = append(r.Conflicts, strings.TrimPrefix(k, "\x00"))
			pick(o, ook)
		}
	}
	return r
}

func splitLines(b []byte) []string {
	s := strings.TrimRight(string(b), "\n")
	if s == "" {
		return nil
	}
	return strings.Split(s, "\n")
}

// keyedFile is an account file and what to run after rewriting it.
type keyedFile struct {
	rel  string // below the root, "etc/master.passwd"
	mode string
}

var keyedFiles = []keyedFile{{"etc/master.passwd", "600"}, {"etc/group", "644"}}

// mergeEtc merges the target generation's /etc into the jail's persistent
// /etc. It returns an api.CodeConflict error naming the files when anything
// conflicts, and leaves rolling the datasets back to the caller (the plan).
func (s *Service) mergeEtc(ctx context.Context, in MergeInput, target string, from string) error {
	mc := s.Cfg.merge().names()
	oldTar, newTar := path.Join(in.Work, "old-etc.tar"), path.Join(in.Work, "new-etc.tar")
	edir, log := path.Join(in.Work, "etcupdate"), path.Join(in.Work, "etcupdate.log")
	if err := s.Files.MkdirAll(ctx, edir); err != nil {
		return err
	}
	run := func(argv ...string) ([]byte, error) {
		out, err := s.Exec.Run(ctx, argv)
		if err != nil {
			return out, fmt.Errorf("%s: %w: %s", strings.Join(argv, " "), err, strings.TrimSpace(string(out)))
		}
		return out, nil
	}
	// What the account files looked like on the three sides, before etcupdate
	// touches the jail's copy.
	type three struct{ base, ours, theirs []string }
	acct := map[string]three{}
	for _, kf := range keyedFiles {
		var t three
		read := func(root string) ([]string, error) {
			b, err := s.Files.ReadFile(ctx, path.Join(root, kf.rel))
			if err != nil {
				if ok, _ := s.Files.Exists(ctx, path.Join(root, kf.rel)); !ok {
					return nil, nil // a generation without the file
				}
				return nil, err
			}
			return splitLines(b), nil
		}
		var err error
		if t.base, err = read(in.OldRoot); err != nil {
			return err
		}
		if t.ours, err = read(in.DestRoot); err != nil {
			return err
		}
		if t.theirs, err = read(in.NewRoot); err != nil {
			return err
		}
		acct[kf.rel] = t
	}
	if _, err := run(mc.Tar, "-C", in.OldRoot, "-cf", oldTar, "./etc"); err != nil {
		return err
	}
	if _, err := run(mc.Tar, "-C", in.NewRoot, "-cf", newTar, "./etc"); err != nil {
		return err
	}
	if _, err := run(mc.Etcupdate, "extract", "-d", edir, "-t", oldTar, "-D", in.DestRoot); err != nil {
		return err
	}
	out, err := s.Exec.Run(ctx, []string{mc.Etcupdate, "-d", edir, "-t", newTar, "-D", in.DestRoot, "-L", log})
	conflicts, _ := ParseEtcupdate(out)
	var files []string
	for _, c := range conflicts {
		if !accountFiles[c] {
			files = append(files, c)
		}
	}
	sort.Strings(files)
	if len(files) > 0 {
		return mergeConflict(target, from, files)
	}
	if err != nil && len(conflicts) == 0 {
		return fmt.Errorf("merge %s: %w: %s", mc.Etcupdate, err, strings.TrimSpace(string(out)))
	}
	// Account files: rewritten from the keyed merge whatever etcupdate did.
	// All merges are computed before anything is written, so a conflict
	// leaves the files as etcupdate left them (the plan rolls the datasets back).
	type outFile struct {
		kf    keyedFile
		lines []string
	}
	var outs []outFile
	var keyConflicts []string
	for _, kf := range keyedFiles {
		t := acct[kf.rel]
		if t.base == nil && t.ours == nil && t.theirs == nil {
			continue
		}
		r := Merge3Keyed(t.base, t.ours, t.theirs, PasswdKey)
		for _, k := range r.Conflicts {
			keyConflicts = append(keyConflicts, "/"+kf.rel+":"+k)
		}
		outs = append(outs, outFile{kf, r.Lines})
	}
	if len(keyConflicts) > 0 {
		sort.Strings(keyConflicts)
		return mergeConflict(target, from, keyConflicts)
	}
	for _, o := range outs {
		dst := path.Join(in.DestRoot, o.kf.rel)
		if err := s.Files.WriteAtomic(ctx, dst, []byte(strings.Join(o.lines, "\n")+"\n")); err != nil {
			return err
		}
		if _, err := run("chmod", o.kf.mode, dst); err != nil {
			return err
		}
	}
	// passwd, pwd.db and spwd.db follow master.passwd.
	etc := path.Join(in.DestRoot, "etc")
	if _, err := run(mc.PwdMkdb, "-p", "-d", etc, path.Join(etc, "master.passwd")); err != nil {
		return err
	}
	return nil
}

func mergeConflict(target, from string, files []string) error {
	return api.Errorf(api.CodeConflict, "merging /etc into %s has %d conflicting files; the jail stays on %s", target, len(files), from).
		WithDetail("reason", "etc_merge_conflict").
		WithDetail("files", strings.Join(files, ",")).
		WithHint("resolve the files in the jail's /etc and upgrade again")
}
